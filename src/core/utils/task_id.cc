auto randomGenerator() -> std::mt19937_64& {
  thread_local std::mt19937_64 generator{std::random_device{}()};
  return generator;
}

auto randomSuffix() -> std::string {
  static constexpr std::string_view kChars = "abcdefghijklmnopqrstuvwxyz0123456789";
  static constexpr int kSuffixLength = 8;
  std::string result(kSuffixLength, ' ');
  auto& gen = randomGenerator();
  std::uniform_int_distribution<size_t> dist(0, kChars.size() - 1);
  for (int i = 0; i < kSuffixLength; ++i) {
    result[i] = kChars[dist(gen)];
  }
  return result;
}

