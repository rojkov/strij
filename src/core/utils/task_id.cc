auto GenerateTaskId() -> std::string {
  auto& gen = randomGenerator();
  std::uniform_int_distribution<size_t> adj_dist(0, kAdjectives.size() - 1);
  std::uniform_int_distribution<size_t> noun_dist(0, kNouns.size() - 1);
  std::uniform_int_distribution<size_t> verb_dist(0, kVerbs.size() - 1);

  return std::string{kAdjectives[adj_dist(gen)]} + '_'
       + std::string{kNouns[noun_dist(gen)]} + '_'
       + std::string{kVerbs[verb_dist(gen)]} + '_'
       + randomSuffix();
}

